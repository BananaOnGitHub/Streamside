"""Generate the compiled immutable manifest bytes and SHA-256 trust pin."""
import argparse
import hashlib
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parent.parent
SOURCE=ROOT/'diagnostics/investigations/rn-chat-gaps/5.json'
OUTPUT=ROOT/'src/TASInvestigationRegistry.h'
INDEX=ROOT/'diagnostics/registry/v1/index.json'
def pairs(items):
    result={}
    for key,value in items:
        if key in result:raise ValueError('Duplicate JSON key: '+key)
        result[key]=value
    return result
def generated():
    data=SOURCE.read_bytes()
    if not 0<len(data)<=16384:raise ValueError('Manifest byte budget')
    json.loads(data,object_pairs_hook=pairs,parse_constant=lambda _:(_ for _ in ()).throw(ValueError('Nonfinite number')))
    digest=hashlib.sha256(data).digest()
    rows=['/* Generated by tools/generate_investigation_registry.py; exact bytes, no executable configuration. */','#ifndef TAS_INVESTIGATION_REGISTRY_H','#define TAS_INVESTIGATION_REGISTRY_H','#define TAS_INV_MANIFEST_SHA256 \"'+digest.hex()+'\"','static const unsigned char tas_inv_manifest_sha256[32]={'+','.join(map(str,digest))+'};','static const unsigned char tas_inv_manifest_bytes[]={']
    rows += [' '+','.join(map(str,data[i:i+24]))+',' for i in range(0,len(data),24)]
    rows += ['};','#endif','']
    return '\n'.join(rows)
def main():
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args();text=generated()
    index=json.dumps({'schema_version':1,'registry_version':5,'entries':[{'id':'rn-chat-gaps','manifest_version':5,'path':'diagnostics/investigations/rn-chat-gaps/5.json','sha256':hashlib.sha256(SOURCE.read_bytes()).hexdigest()}]},indent=2)+'\n'
    if a.check:
        if not OUTPUT.exists() or OUTPUT.read_text()!=text:raise SystemExit('Stale bundled investigation registry')
        if not INDEX.exists() or INDEX.read_text()!=index:raise SystemExit('Stale bundled registry index')
    else:
        OUTPUT.write_text(text);INDEX.parent.mkdir(parents=True,exist_ok=True);INDEX.write_text(index)
if __name__=='__main__':main()
